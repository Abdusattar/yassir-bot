def resolve_page(page_number):
    """Возвращает список [(surah, start_ayah, end_ayah), ...] для номера
    страницы (обычно один элемент, два - на единственной переходной
    странице 106, см. модульный docstring), или None, если номер вне
    диапазона 2-221."""
    entry = PAGES.get(page_number)
    if entry is None:
        return None
    return [(surah, rng[0], rng[1]) for surah, rng in sorted(entry.items())]


def last_ayah_on_page(page_number):
    """(surah, ayah) - самая поздняя по порядку чтения точка на странице
    (последняя сура/аят из resolve_page). Нужна как "докуда дошла
    закладка" для пула тренажёра, который теперь охватывает несколько
    сур подряд (core/mufradat.py:get_words_up_to_page)."""
    entries = resolve_page(page_number)
    if not entries:
        return None
    surah, _, end_ayah = entries[-1]
    return surah, end_ayah


# Обратный индекс (surah, ayah) -> page, построен один раз при загрузке
# модуля - всего ~1466 аятов в диапазоне 2-221, тривиально быстро. Раньше
# page_for_ayah линейно сканировал все 220 записей PAGES на КАЖДЫЙ вызов -
# на полном пуле (27609 слов закладки, стр. 221) это давало ощутимую
# задержку на каждый тап тренажёра (_scaled_repeat_threshold вызывает
# page_for_ayah на каждое слово пула) - измерено эмпирически на проде
# после загрузки сур 3-10, 18.08.2026 (advisor поймал риск заранее).
_AYAH_TO_PAGE = {
    (surah, ayah): page
    for page, entry in PAGES.items()
    for surah, (start, end) in entry.items()
    for ayah in range(start, end + 1)
}


def page_for_ayah(surah_number, ayah_number):
    """Обратная функция - номер страницы, на которой лежит (surah, ayah).
    Нужна surah_number явно (не только ayah_number, как было до
    18.08.2026, пока была только Бакара) - при нескольких сурах номера
    аятов повторяются в разных сурах, без suры это неоднозначно."""
    return _AYAH_TO_PAGE.get((surah_number, ayah_number))
