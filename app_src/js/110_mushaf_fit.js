  // Худшее отношение "нужно / есть" среди строк. <= 1 - всё влезло.
  function mushafWorstOverflowRatio(lines) {
    var worst = 1, box = document.getElementById('ayah-text');
    // Подписи лёжа не в счёт (30.10.2026): сразу после смены кегля у них
    // ещё рамки от прошлого (glossFit - в следующем кадре).
    box.classList.add('gl-off');
    for (var i = 0; i < lines.length; i++) {
      var w = lines[i].clientWidth;
      if (!w) continue;
      if (lines[i].scrollWidth > w + MUSHAF_VERIFY_TOLERANCE) {
        var ratio = lines[i].scrollWidth / w;
        if (ratio > worst) worst = ratio;
      }
    }
    box.classList.remove('gl-off');
    return worst;
  }

  // Возвращает, что вышло ({font, capped, lines, avail}), или null, если
  // мерить было нечего. trustCap - принять потолок на полном листе (см.
  // MUSHAF_FULL_PAGE_LINES).
  function clampFontToFit(trustCap) {
    var el = document.getElementById('ayah-text');
    var lines = el.querySelectorAll('.mushaf-line');
    if (!lines.length) return null;
    el.style.maxWidth = '';   // прошлое сужение по высоте не должно влиять на замер
    var avail = el.clientWidth;
    if (!avail) return null;   // #app ещё display:none - меряем позже, см. dash-mushaf

    // .measuring снимает space-between: строка перестаёт растягиваться,
    // и scrollWidth становится настоящей суммой ширин слов.
    el.classList.add('measuring');
    el.style.fontSize = MUSHAF_MEASURE_BASE + 'px';
    var maxW = 0;
    for (var i = 0; i < lines.length; i++) {
      if (lines[i].scrollWidth > maxW) maxW = lines[i].scrollWidth;
    }
    el.classList.remove('measuring');
    if (!maxW) return null;

    var fitted = MUSHAF_MEASURE_BASE * (avail / maxW) * MUSHAF_FIT_SAFETY;
    fitted = Math.min(mushafMaxFont(), Math.max(MUSHAF_MIN_FONT_SIZE, fitted));
    var full = lines.length >= MUSHAF_FULL_PAGE_LINES;
    var capped = full && fitted >= mushafMaxFont();
    if (capped && !trustCap && mushafFitTrusted) fitted = mushafFitTrusted;
    else if (full && !capped) mushafFitTrusted = fitted;
    el.style.fontSize = fitted.toFixed(1) + 'px';

    // Самопроверка (см. MUSHAF_VERIFY_* выше). Меряем УЖЕ ОТРИСОВАННЫЕ
    // строки как есть, без .measuring: нас интересует не натуральная ширина
    // слов, а факт "вылезло за край или нет" при боевом justify.
    for (var step = 0; step < MUSHAF_VERIFY_STEPS; step++) {
      if (fitted <= MUSHAF_MIN_FONT_SIZE) break;
      var over = mushafWorstOverflowRatio(lines);
      if (over <= 1) break;
      var shrink = Math.max(MUSHAF_VERIFY_MAX_STEP, (1 / over) * MUSHAF_VERIFY_SAFETY);
      fitted = Math.max(MUSHAF_MIN_FONT_SIZE, fitted * shrink);
      el.style.fontSize = fitted.toFixed(1) + 'px';
    }
    el.setAttribute('data-fit-base', fitted.toFixed(1));   // кегль по ширине - для предела по высоте
    return { font: fitted, capped: capped, lines: lines.length, avail: avail, maxW: maxW };
  }

  // Подгонка с повторами (см. MUSHAF_REFIT_DELAYS). Каждый вызов - новая
  // отрисовка: повторы предыдущей замолкают, чтобы не мерить чужую страницу.
  //
  // Есть лист в таблице - кегль ставится сразу, ранние повторы его не
  // трогают (на айфоне шрифт мог ещё не лечь, им не верим), а последний
  // сверяет: согласен - кегль остаётся тем же числом, картинка не дёргается;
  // не согласен (таблица устарела, чужой движок на первом листе) - правит и
  // шлёт отчёт. Он же учит mushafFitK.
  //
  // Листа в таблице нет - как до неё: первый удавшийся замер запоминается;
  // если поздний дал другой размер (или первый упёрся в потолок и так и не
  // поправился) - уходит отчёт.
  /* Второй предел кегля - по высоте (11.11.2026, нижняя панель в мусхафе,
     перенос из прототипа). Только в режиме «Страница» с панелью и только
     стоя: лист должен влезать целиком, а не скроллиться; лёжа лист
     скроллится по замыслу (21.09.2026). Шаг идёт ПОСЛЕ подбора по ширине
     (табличного или замером) и не трогает его: clampFontToFit и сверка с
     таблицей остаются как были. Кегль ужат - колонка сужается в той же
     пропорции, иначе justify растянул бы слова огромными пробелами. */
  function mushafHeightCap() {
    var el = document.getElementById('ayah-text');
    var wrap = document.getElementById('page-wrap');
    var app = document.getElementById('app');
    if (!el || !wrap) return;
    el.style.maxWidth = '';
    if (!document.body.classList.contains('tabs-mushaf') || app.classList.contains('land')) return;
    // base - кегль по ширине. Сверка с таблицей возвращает «прежний» кегль,
    // а он мог быть уже ужат этим же шагом, поэтому кегль по ширине
    // запоминаем в data-fit-base; подбор по ширине его сбрасывает.
    var cur = parseFloat(el.style.fontSize);
    if (!cur || !wrap.clientHeight) return;
    var base = parseFloat(el.getAttribute('data-fit-base')) || cur;
    var full = el.clientWidth, font = cur;
    for (var i = 0; i < 2; i++) {
      var room = wrap.clientHeight - 12, need = el.scrollHeight;
      if (!(need > room) || font <= MUSHAF_MIN_FONT_SIZE) break;
      font = Math.max(MUSHAF_MIN_FONT_SIZE, font * (room / need) * 0.99);
      el.style.fontSize = font.toFixed(1) + 'px';
    }
    if (font < base) el.style.maxWidth = Math.round(full * font / base) + 'px';
  }

  function mushafFitSchedule() {
    var run = ++mushafFitRun;
    var predicted = mushafFitPredict();
    if (predicted) mushafHeightCap();
    var first = predicted, reported = false;
    var tick = function (why, last) {
      if (run !== mushafFitRun) return;
      if (predicted) {
        if (last) { mushafFitVerify(predicted, why); mushafHeightCap(); }
        return;
      }
      var r = clampFontToFit(last);
      mushafHeightCap();
      if (!r) return;
      if (!first) { first = r; first.why = why; return; }
      var moved = Math.abs(r.font - first.font) > 0.5;
      if (!reported && (moved || (last && first.capped))) {
        reported = true;
        mushafFitReport(first, r, why);
      }
    };
    requestAnimationFrame(function () {
      requestAnimationFrame(function () { tick('frame', false); });
    });
    MUSHAF_REFIT_DELAYS.forEach(function (ms, i) {
      setTimeout(function () {
        tick(ms + 'ms', i === MUSHAF_REFIT_DELAYS.length - 1);
      }, ms);
    });
  }

  // Поздняя сверка кегля из таблицы с настоящим замером. Всё внутри одной
  // задачи, без кадра между записями: даже если замер временно поставил
  // своё число, а мы вернули табличное, на экран попадает только итог.
  function mushafFitVerify(predicted, why) {
    var el = document.getElementById('ayah-text');
    var keep = el.style.fontSize;
    var r = clampFontToFit(true);
    if (!r) return;
    r.k = r.maxW ? r.maxW / predicted.w : 0;
    /* Замер, разошедшийся с таблицей больше, чем бывает между движками,
       - сломанный замер, а не другой телефон (13.09.2026, Муслим из Н-1,
       Safari 18.7.5): таблица дала верные 22.3/22.4, а сверка через
       полторы секунды - 34 (потолок) на стр. 51, 5 и 6, и текст ушёл за
       край. Замер scrollWidth строк на этом айфоне врёт и после раскладки,
       так что причина не во времени. Таблица остаётся, в отчёт уходит
       вторая мерка - по прямоугольникам самих слов (mushafRectWidth), чтобы
       по журналу было видно, что именно врёт. */
    if (!(r.k >= MUSHAF_FIT_K_MIN && r.k <= MUSHAF_FIT_K_MAX)) {
      var d = mushafRectWidth();
      r.rect = d.rect; r.fs = d.fs; r.w1 = d.w1; r.w1n = d.w1n;
      el.style.fontSize = keep;
      mushafFitReport(predicted, r, why + ' bad');
      return;
    }
    mushafFitLearn(r.k);
    if (Math.abs(r.font - predicted.font) <= MUSHAF_FIT_AGREE) {
      el.style.fontSize = keep;
      // Согласие - только если табличный кегль правда влезает: запас
      // MUSHAF_FIT_SAFETY полтора процента, допуск в полпикселя больше.
      if (mushafWorstOverflowRatio(el.querySelectorAll('.mushaf-line')) <= 1) return;
      el.style.fontSize = r.font.toFixed(1) + 'px';
    }
    mushafFitReport(predicted, r, why);
  }

  // Ширина самой длинной строки при MUSHAF_MEASURE_BASE - не по scrollWidth,
  // а от левого края крайнего слова до правого края другого. Только для
  // отчёта: проверить на живом айфоне, какая из двух мерок врёт.
  function mushafRectWidth() {
    var el = document.getElementById('ayah-text');
    var lines = el.querySelectorAll('.mushaf-line');
    var first = lines[0] && lines[0].children[0];
    var keep = el.style.fontSize;
    // Ширина первого слова ДО замера - сравнить с ним же при 40px: если
    // отношение ~1, кегль 40px до раскладки не дошёл; если ~40/кегль, дошёл,
    // и тогда врёт что-то другое (отчёт Муслима 13.09: rect=369 при таблице
    // 659 - это ровно 659 × 22.4 / 40, но и «слова ужались в контейнер»
    // дало бы те же 369; по одному числу не различить).
    var w1n = first ? first.getBoundingClientRect().width : 0;
    el.classList.add('measuring');
    el.style.fontSize = MUSHAF_MEASURE_BASE + 'px';
    var fs = parseFloat(getComputedStyle(el).fontSize);
    var w1 = first ? first.getBoundingClientRect().width : 0;
    var maxW = 0;
    for (var i = 0; i < lines.length; i++) {
      var kids = lines[i].children, lo = Infinity, hi = -Infinity;
      for (var j = 0; j < kids.length; j++) {
        var b = kids[j].getBoundingClientRect();
        if (b.left < lo) lo = b.left;
        if (b.right > hi) hi = b.right;
      }
      if (hi - lo > maxW) maxW = hi - lo;
    }
    el.classList.remove('measuring');
    el.style.fontSize = keep;
    return { rect: Math.round(maxW), fs: Math.round(fs * 10) / 10,
             w1: Math.round(w1 * 10) / 10, w1n: Math.round(w1n * 10) / 10 };
  }

  // Отчёт на сервер (13.09.2026): поздняя перепроверка поправила кегль -
  // значит, первый замер соврал. Айфон с машины не воспроизвести, а так после
  // выкладки по журналу видно, на каких телефонах и насколько, без снимков.
  // Тихо: сбой отчёта студента не касается, баннер «нет связи» не трогаем.
  function mushafFitReport(first, final, why) {
    if (typeof apiCall !== 'function') return;
    apiCall('/fitlog', { method: 'POST', quiet: true, body: {
      page: currentPage, lines: first.lines, avail: first.avail,
      first: Math.round(first.font * 10) / 10, first_why: first.why,
      first_capped: !!first.capped,
      final: Math.round(final.font * 10) / 10, final_why: why,
      // Сырые мерки при 40px: таблица, scrollWidth, прямоугольники слов.
      table: first.w, scroll: final.maxW, rect: final.rect,
      fs: final.fs, w1: final.w1, w1n: final.w1n,
      k: final.k ? Math.round(final.k * 1000) / 1000 : undefined
    } }).catch(function () {});
  }

